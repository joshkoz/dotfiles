#!/usr/bin/env bash
set -euo pipefail

config_home="${XDG_CONFIG_HOME:-$HOME/.config}"
state_file="$config_home/theme-picker/current"

usage() {
  printf 'Usage: %s [THEME|list|current]\n' "${0##*/}" >&2
}

ghostty_theme_names() {
  if ! command -v ghostty >/dev/null 2>&1; then
    printf 'ghostty is required to list source themes.\n' >&2
    exit 1
    return
  fi

  ghostty +list-themes | awk '{ sub(/ \([^)]+\)$/, ""); print }'
}

current_theme() {
  if [[ -f "$state_file" ]]; then
    while IFS= read -r current_theme; do
      printf '%s\n' "$current_theme"
    done < "$state_file"
    return
  fi

  printf 'Catppuccin Mocha\n'
}

pick_theme() {
  if ! command -v wofi >/dev/null 2>&1; then
    printf 'wofi is required to pick a theme interactively. Use `%s list` first.\n' "${0##*/}" >&2
    exit 1
  fi

  ghostty_theme_names | wofi --conf "$config_home/wofi/config" --style "$config_home/wofi/style.css" --dmenu -i -p "Theme"
}

ghostty_theme_file() {
  local theme="$1"
  local path

  for path in \
    "$config_home/ghostty/themes/$theme" \
    "$HOME/.local/share/ghostty/themes/$theme" \
    "/usr/share/ghostty/themes/$theme"; do
    if [[ -f "$path" ]]; then
      printf '%s\n' "$path"
      return
    fi
  done

  return 1
}

render_waybar_style() {
  local theme_file="$1"
  local waybar_theme="$config_home/waybar/theme.css"

  if [[ -L "$waybar_theme" ]]; then
    rm "$waybar_theme"
  fi

  awk '
    /^[[:space:]]*palette[[:space:]]*=/ {
      value = $0
      sub(/^[^=]*=[[:space:]]*/, "", value)
      split(value, parts, "=")
      palette[parts[1]] = parts[2]
    }
    /^[[:space:]]*background[[:space:]]*=/ { base = $3 }
    /^[[:space:]]*foreground[[:space:]]*=/ { text = $3 }
    /^[[:space:]]*selection-background[[:space:]]*=/ { selection = $3 }
    END {
      if (!base) base = "#1e1e2e"
      if (!text) text = "#cdd6f4"
      if (!selection) selection = palette[8] ? palette[8] : base

      printf "@define-color base   %s;\n", base
      printf "@define-color mantle %s;\n", base
      printf "@define-color crust  %s;\n\n", palette[0] ? palette[0] : base
      printf "@define-color text     %s;\n", text
      printf "@define-color subtext0 %s;\n", palette[7] ? palette[7] : text
      printf "@define-color subtext1 %s;\n\n", text
      printf "@define-color surface0 %s;\n", selection
      printf "@define-color surface1 %s;\n", palette[8] ? palette[8] : selection
      printf "@define-color surface2 %s;\n\n", palette[8] ? palette[8] : selection
      printf "@define-color overlay0 %s;\n", palette[8] ? palette[8] : selection
      printf "@define-color overlay1 %s;\n", palette[7] ? palette[7] : text
      printf "@define-color overlay2 %s;\n\n", text
      printf "@define-color blue      %s;\n", palette[4] ? palette[4] : text
      printf "@define-color lavender  %s;\n", palette[12] ? palette[12] : (palette[4] ? palette[4] : text)
      printf "@define-color sapphire  %s;\n", palette[4] ? palette[4] : text
      printf "@define-color sky       %s;\n", palette[14] ? palette[14] : (palette[6] ? palette[6] : text)
      printf "@define-color teal      %s;\n", palette[6] ? palette[6] : text
      printf "@define-color green     %s;\n", palette[2] ? palette[2] : text
      printf "@define-color yellow    %s;\n", palette[3] ? palette[3] : text
      printf "@define-color peach     %s;\n", palette[11] ? palette[11] : (palette[3] ? palette[3] : text)
      printf "@define-color maroon    %s;\n", palette[1] ? palette[1] : text
      printf "@define-color red       %s;\n", palette[9] ? palette[9] : (palette[1] ? palette[1] : text)
      printf "@define-color mauve     %s;\n", palette[5] ? palette[5] : text
      printf "@define-color pink      %s;\n", palette[13] ? palette[13] : (palette[5] ? palette[5] : text)
      printf "@define-color flamingo  %s;\n", palette[13] ? palette[13] : (palette[5] ? palette[5] : text)
      printf "@define-color rosewater %s;\n", palette[15] ? palette[15] : text
    }
  ' "$theme_file" > "$waybar_theme"
  chmod 0644 "$waybar_theme"
}

render_dunst_config() {
  local theme_file="$1"
  local dunst_config="$config_home/dunst/dunstrc"
  local tmp

  tmp="$(mktemp)"

  if [[ -f "$dunst_config" ]]; then
    awk '
      /^# BEGIN theme-picker$/ { skip = 1; next }
      /^# END theme-picker$/ { skip = 0; next }
      !skip { print }
    ' "$dunst_config" > "$tmp"
  else
    printf '# Generated by theme-picker\n' > "$tmp"
  fi

  awk '
    /^[[:space:]]*palette[[:space:]]*=/ {
      value = $0
      sub(/^[^=]*=[[:space:]]*/, "", value)
      split(value, parts, "=")
      palette[parts[1]] = parts[2]
    }
    /^[[:space:]]*background[[:space:]]*=/ { base = $3 }
    /^[[:space:]]*foreground[[:space:]]*=/ { text = $3 }
    /^[[:space:]]*selection-background[[:space:]]*=/ { selection = $3 }
    END {
      if (!base) base = "#1e1e2e"
      if (!text) text = "#cdd6f4"
      if (!selection) selection = palette[8] ? palette[8] : base
      accent = palette[4] ? palette[4] : text
      critical = palette[9] ? palette[9] : (palette[1] ? palette[1] : text)

      print ""
      print "# BEGIN theme-picker"
      print "[global]"
      printf "    frame_color = \"%s\"\n", accent
      printf "    background = \"%s\"\n", base
      printf "    foreground = \"%s\"\n\n", text
      print "[urgency_low]"
      printf "    background = \"%s\"\n", base
      printf "    foreground = \"%s\"\n", text
      printf "    frame_color = \"%s\"\n\n", selection
      print "[urgency_normal]"
      printf "    background = \"%s\"\n", base
      printf "    foreground = \"%s\"\n", text
      printf "    frame_color = \"%s\"\n\n", accent
      print "[urgency_critical]"
      printf "    background = \"%s\"\n", critical
      printf "    foreground = \"%s\"\n", base
      printf "    frame_color = \"%s\"\n", critical
      print "# END theme-picker"
    }
  ' "$theme_file" >> "$tmp"

  mv "$tmp" "$dunst_config"
  chmod 0644 "$dunst_config"
}

render_wofi_style() {
  local theme_file="$1"
  local wofi_style="$config_home/wofi/style.css"
  local tmp

  tmp="$(mktemp)"

  awk '
    /^[[:space:]]*palette[[:space:]]*=/ {
      value = $0
      sub(/^[^=]*=[[:space:]]*/, "", value)
      split(value, parts, "=")
      palette[parts[1]] = parts[2]
    }
    /^[[:space:]]*background[[:space:]]*=/ { base = $3 }
    /^[[:space:]]*foreground[[:space:]]*=/ { text = $3 }
    /^[[:space:]]*selection-background[[:space:]]*=/ { selection = $3 }
    END {
      if (!base) base = "#1e1e2e"
      if (!text) text = "#cdd6f4"
      if (!selection) selection = palette[8] ? palette[8] : base
      printf "@define-color base            %s;\n", base
      printf "@define-color text            %s;\n", text
      printf "@define-color subtext         %s;\n", palette[7] ? palette[7] : text
      printf "@define-color vicinae-border  %s;\n", palette[8] ? palette[8] : selection
      printf "@define-color vicinae-sep     %s;\n", selection
      printf "@define-color vicinae-sel     %s;\n", text
      printf "@define-color vicinae-sel-text %s;\n\n", base
    }
  ' "$theme_file" > "$tmp"

  if [[ -f "$wofi_style" ]]; then
    awk '
      /^[[:space:]]*@define-color[[:space:]]/ { next }
      /^[[:space:]]*@import[[:space:]]/ { next }
      { print }
    ' "$wofi_style" >> "$tmp"
  fi

  mv "$tmp" "$wofi_style"
  chmod 0644 "$wofi_style"
}

apply_theme() {
  local selected_theme="$1"
  local theme_file

  if command -v ghostty >/dev/null 2>&1 && ! ghostty_theme_names | awk -v theme="$selected_theme" '$0 == theme { found = 1 } END { exit found ? 0 : 1 }'; then
    printf 'Unknown Ghostty source theme: %s\n\nAvailable themes:\n' "$selected_theme" >&2
    ghostty_theme_names >&2
    exit 1
  fi

  if ! theme_file="$(ghostty_theme_file "$selected_theme")"; then
    printf 'Could not find Ghostty theme file for: %s\n' "$selected_theme" >&2
    exit 1
  fi

  mkdir -p "$config_home/waybar" "$config_home/wofi" "$config_home/dunst" "${state_file%/*}"

  render_waybar_style "$theme_file"
  render_wofi_style "$theme_file"
  render_dunst_config "$theme_file"

  printf '%s\n' "$selected_theme" > "$state_file"

  systemctl --user restart waybar.service >/dev/null 2>&1 || pkill -SIGUSR2 waybar >/dev/null 2>&1 || true
  dunstctl reload >/dev/null 2>&1 || systemctl --user restart dunst.service >/dev/null 2>&1 || true

  pkill -x wofi >/dev/null 2>&1 || true

  if command -v dunstify >/dev/null 2>&1; then
    dunstify "Desktop theme changed" "$selected_theme"
  fi

  printf 'Applied desktop theme from Ghostty source: %s\n' "$selected_theme"
}

case "${1:-}" in
  list)
    ghostty_theme_names
    ;;
  current)
    current_theme
    ;;
  -h|--help)
    usage
    ;;
  "")
    selected="$(pick_theme)"
    [[ -n "$selected" ]] || exit 0
    apply_theme "$selected"
    ;;
  *)
    apply_theme "$1"
    ;;
esac
