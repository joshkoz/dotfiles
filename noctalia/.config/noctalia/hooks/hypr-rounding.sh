#!/usr/bin/env bash
# Keep Hyprland's window rounding in step with Noctalia's "Corner roundness" slider
# (shell.corner_radius_scale). Noctalia's panels use 12px x that scale (Style::radiusXl),
# so windows get the same radius. Writes hypr/noctalia_rounding.lua (read by hyprland.lua)
# and reloads Hyprland when the value changes.
# Run by noctalia's `started` hook and by noctalia-hypr-rounding.path when settings change.
set -euo pipefail

scale="$(noctalia msg config-get shell.corner_radius_scale 2>/dev/null | tail -1)"
[[ "$scale" =~ ^[0-9]+(\.[0-9]+)?$ ]] || exit 0

radius="$(awk -v s="$scale" 'BEGIN { printf "%d", 12 * s + 0.5 }')"
out="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/noctalia_rounding.lua"
content="-- Generated by noctalia/hooks/hypr-rounding.sh from shell.corner_radius_scale = $scale
return $radius"

[[ -f "$out" && "$(<"$out")" == "$content" ]] && exit 0
printf '%s\n' "$content" >"$out"
hyprctl reload >/dev/null 2>&1 || true
